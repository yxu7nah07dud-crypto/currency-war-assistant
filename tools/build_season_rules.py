"""Derive season 2 rule facts from the pinned local 4.7 research files."""
import hashlib
import json
from pathlib import Path
from pprint import pformat
import re
import sys
import unicodedata

SOURCE_COMMIT = "2c8a218502ebfccaf6e01675b0bdf6948d723bbb"


def effect_key(text):
    text = unicodedata.normalize("NFKC", re.sub(r"<[^>]+>", "", text))
    return hashlib.sha256("".join(c for c in text if c.isalnum()).encode("utf8")).hexdigest()


def build(directory, output):
    def read(name):
        return json.loads((directory / f"{name}.json").read_text(encoding="utf8"))

    text = read("TextMapCHS")

    def label(record):
        return text[str(record["Hash"])]

    affixes = {
        row["ID"]: (label(row["AffixName"]), tuple(part.get("Value", 0) for part in row["EffectParamList"]))
        for row in read("GridFightAffixConfig")
    }
    scaling = {}
    for row in read("GridFightEnemyDifficultyLv"):
        level, chapter = row.get("EnemyDifficultyLevel", 0), row["ChapterID"]
        scaling.setdefault(level, {})[chapter] = tuple(
            row[key].get("Value", 0) for key in
            ("AttackRatio", "HPRatio", "SpeedRatio", "AllDamageReduce")
        )
    scaling = {level: tuple(planes[i] for i in (1, 2, 3)) for level, planes in scaling.items()}
    ranks = {label(row["DivisionName"]): label(row["DivisionAbbr"])
             for row in read("GridFightDivisionLevelShow")
             if row["SeasonID"] == 2 and "DivisionAbbr" in row}
    ranks = {name: code for name, code in ranks.items() if re.fullmatch(r"A[0-8]", code)}
    ranks_by_level = {int(code[1:]) + 1: code for code in ranks.values()}
    divisions = {}
    for row in read("GridFightDivisionStage"):
        season_and_rank, ordinal = divmod(row["DivisionID"], 100)
        season, rank = divmod(season_and_rank, 100)
        if season == 2 and rank in ranks_by_level:
            divisions.setdefault(ranks_by_level[rank], {})[ordinal] = row.get("EnemyDifficultyLevel", 0)
    traits = {str(row["TraitID"]) for row in read("GridFightSeasonTraitShow") if row["SeasonID"] == 2}
    thresholds = {}
    for row in read("GridFightTraitLayer"):
        key = str(row["TraitID"])
        if key in traits and row["Layer"] > 0:
            thresholds[key] = min(thresholds.get(key, row["Layer"]), row["Layer"])
    levels = {row["GridFightLevel"]: (
        row.get("LevelUpExp"), row["AvatarMaxNumber"],
        tuple(row.get(f"Rarity{i}Weight", 0) for i in range(1, 6)),
    ) for row in read("GridFightLevelV2")}
    prices = {row["Rarity"]: row["BuyGoldStar1"] for row in read("GridFightShopPrice")}
    pet_effects = {row["ID"]: row for row in read("GridFightPetPalEff")}
    partners = {
        label(row["Name"]): tuple(row.get("EffIDList", ()))
        for row in read("GridFightPetPal") if row.get("EffIDList")
        and all(identifier in pet_effects for identifier in row["EffIDList"])
    }
    effects = {key: effect_key(label(row["SwitchDesc"]))
               for key, row in pet_effects.items() if row.get("SwitchDesc")}
    spotlight_difficulty = {str(row["ID"]): row["EnemyDiffLvAdd"] for row in read("GridFightSpotLight")
                            if row.get("EnemyDiffLvAdd")}
    rules = dict(SOURCE_COMMIT=SOURCE_COMMIT, AFFIXES=affixes, ENEMY_SCALING=scaling,
                 RANKS=ranks, DIVISIONS=divisions, TRAIT_THRESHOLDS=thresholds,
                 LEVELS=levels, SHOP_PRICES=prices, PARTNERS=partners, VOYAGE_EFFECT_KEYS=effects,
                 SPOTLIGHT_DIFFICULTY=spotlight_difficulty)
    output.write_text(
        '"""Season 2 rule facts generated by tools/build_season_rules.py."""\n\n'
        + "\n\n".join(f"{name} = {pformat(value, width=116)}" for name, value in rules.items()) + "\n",
        encoding="utf8",
    )


if __name__ == "__main__":
    build(Path(sys.argv[1]), Path(__file__).resolve().parents[1] / "currency_war_assistant" / "season_data.py")
