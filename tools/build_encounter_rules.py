"""Extract numeric rule facts from a local public game-data snapshot.

Usage: python tools/build_encounter_rules.py PATH_TO_DATA_DIRECTORY
The input directory must contain the four files named below. No artwork,
TextMap, full source descriptions or private game data are bundled.
"""
from pathlib import Path
import json
import sys

COMMIT = "312b4597691e0a29cf9828a15b592757dba86949"
VERSION = "4.6"
SOURCE = "https://github.com/DimbreathBot/TurnBasedGameData"


def build(directory, output):
    def read(name):
        return json.loads((directory / name).read_text(encoding="utf8"))
    text = read("TextMapCHS.json")
    affixes = read("GridFightAffixConfig.json")
    difficulty = read("GridFightEnemyDifficultyLv.json")
    traits = read("GridFightTraitLayer.json")
    lines = [
        '"""Numeric game-rule facts; generated by tools/build_encounter_rules.py.',
        'Descriptions and advice are authored separately in encounter.py/localization.py.',
        'Source files: GridFightAffixConfig, GridFightEnemyDifficultyLv, GridFightTraitLayer.',
        '"""',
        f'RULE_VERSION = {VERSION!r}',
        f'SOURCE_COMMIT = {COMMIT!r}',
        f'SOURCE_URL = {SOURCE + "/tree/" + COMMIT + "/ExcelOutput"!r}',
        '',
        '# ID: (name, numeric parameters in their original units)',
        'AFFIXES = {',
    ]
    for row in affixes:
        name = text[str(row["AffixName"]["Hash"])]
        values = tuple(v.get("Value", 0) for v in row["EffectParamList"])
        lines.append(f'    {row["ID"]}: ({name!r}, {values!r}),')
    lines.extend(['}', '', '# Enemy difficulty: (ATK, HP, SPD) for planes 1, 2, 3.', 'ENEMY_SCALING = {'])
    grouped = {}
    for row in difficulty:
        grouped.setdefault(row.get("EnemyDifficultyLevel", 0), {})[row["ChapterID"]] = tuple(
            row[key].get("Value", 0) for key in ("AttackRatio", "HPRatio", "SpeedRatio"))
    for level, planes in sorted(grouped.items()):
        if set(planes) != {1, 2, 3}:
            raise ValueError(f'Incomplete difficulty {level}')
        lines.append(f'    {level}: {tuple(planes[p] for p in (1, 2, 3))!r},')
    thresholds = {}
    for row in traits:
        identifier = str(row["TraitID"])
        thresholds[identifier] = min(thresholds.get(identifier, row["Layer"]), row["Layer"])
    lines.extend(['}', '', '# Minimum ordinary activation count; special traits are checked separately.',
                  f'TRAIT_THRESHOLDS = {thresholds!r}', ''])
    output.write_text('\n'.join(lines), encoding="utf8")


if __name__ == '__main__':
    build(Path(sys.argv[1]), Path(__file__).resolve().parent.parent / 'currency_war_assistant' / 'encounter_data.py')
